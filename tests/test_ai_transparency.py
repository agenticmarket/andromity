import pytest

from andromity import __version__
from andromity.ci.pr_reviewer import review_footer
from andromity.config import config
from andromity.core.agent import Agent
from andromity.core.events import Done, TextDelta
from andromity.core.export import build_export_data, render_html, render_markdown
from andromity.core.profiles import (
    AI_DISCLOSURE,
    CO_AUTHOR_TRAILER,
    PROFILES,
    assisted_by_trailer,
    get_system_prompt,
)
from andromity.core.provider import sanitize_messages_for_api
from andromity.core.session import Session


def _settings(monkeypatch, **values):
    original_get = config.get

    def fake_get(section, key, default=None, fallback=None):
        if section == "default" and key in values:
            return values[key]
        return original_get(section, key, default, fallback)

    monkeypatch.setattr(config, "get", fake_get)


@pytest.fixture
def session(tmp_path):
    return Session(name="transparency", project_path=str(tmp_path))


@pytest.mark.parametrize("profile", sorted(PROFILES))
def test_every_profile_tells_the_agent_to_disclose_posts_to_other_people(profile):
    prompt = get_system_prompt(profile)
    assert AI_DISCLOSURE in prompt
    assert "drafts you hand back" in prompt


def test_assisted_by_trailer_is_off_by_default(monkeypatch):
    _settings(monkeypatch, include_co_author=True)
    prompt = get_system_prompt("builder", model_id="openai/gpt-5")
    assert "Assisted-by" not in prompt
    assert f"the trailer `{CO_AUTHOR_TRAILER}`" in prompt


def test_assisted_by_trailer_names_version_and_model(monkeypatch):
    _settings(monkeypatch, include_co_author=False, include_assisted_by=True)
    prompt = get_system_prompt("builder", model_id="anthropic/claude-sonnet-4-6")
    expected = f"Assisted-by: Andromity/{__version__} (anthropic/claude-sonnet-4-6)"
    assert assisted_by_trailer("anthropic/claude-sonnet-4-6") == expected
    assert f"the trailer `{expected}`" in prompt
    assert "Co-authored-by" not in prompt


def test_both_trailers_are_requested_together(monkeypatch):
    _settings(monkeypatch, include_co_author=True, include_assisted_by=True)
    prompt = get_system_prompt("coder", model_id="ollama/qwen3")
    assert f"`{CO_AUTHOR_TRAILER}` and `{assisted_by_trailer('ollama/qwen3')}`, one per line" in prompt


def _mock_stream(text):
    async def stream(messages, tools=None, **kwargs):
        yield TextDelta(text=text)
        yield Done(usage={"prompt_tokens": 10, "completion_tokens": 5, "total_tokens": 15})
    return stream


@pytest.mark.asyncio
async def test_answers_record_the_model_without_sending_it_to_providers(session):
    agent = Agent(session, profile="builder", auto_approve=True, provider="openai", model="gpt-5")
    with patch("andromity.core.agent.stream_completion", side_effect=_mock_stream("Hi")):
        async for _ in agent.run("hello"):
            pass
    answer = session.messages[-1]
    assert answer["role"] == "assistant" and answer["model"] == "openai/gpt-5"
    assert all("model" not in m for m in sanitize_messages_for_api(session.messages))


@pytest.mark.asyncio
async def test_model_switch_rewrites_the_assisted_by_trailer(session, monkeypatch):
    _settings(monkeypatch, include_assisted_by=True)
    agent = Agent(session, profile="builder", auto_approve=True, provider="openai", model="gpt-a")
    assert "(openai/gpt-a)" in session.messages[0]["content"]

    agent.model = "gpt-b"
    with patch("andromity.core.agent.stream_completion", side_effect=_mock_stream("Done")):
        async for _ in agent.run("commit this"):
            pass
    system = session.messages[0]["content"]
    assert "(openai/gpt-b)" in system and "(openai/gpt-a)" not in system
    assert session.messages[-1]["model"] == "openai/gpt-b"


def test_exports_mark_ai_output_and_name_each_answers_model(session):
    session.add_message("user", content="Explain a.py")
    session.add_message("assistant", content="It parses config.", model="anthropic/claude-sonnet-4-6")
    session.add_message("user", content="And b.py?")
    session.add_message("assistant", content="It is empty.")
    data = build_export_data(session)

    assert data["generator"] == f"Andromity {__version__}" and data["ai_generated"] is True
    assert [r["model"] for t in data["turns"] for r in t["responses"]] == ["anthropic/claude-sonnet-4-6", ""]
    assert json.loads(json.dumps(data))["generator"] == data["generator"]

    md = render_markdown(data)
    assert f"| **Generated by** | Andromity {__version__} (AI agent) |" in md
    assert "### 🤖 Andromity · `anthropic/claude-sonnet-4-6`" in md
    assert "\n### 🤖 Andromity\n" in md

    page = render_html(data)
    assert f'<meta name="generator" content="Andromity {__version__}">' in page
    assert "🤖 Andromity · <code>anthropic/claude-sonnet-4-6</code>" in page


def test_pr_review_footer_discloses_ai_and_model():
    footer = review_footer("openrouter/deepseek/deepseek-v4.1-flash")
    assert "AI-generated review by [Andromity]" in footer
    assert "using `openrouter/deepseek/deepseek-v4.1-flash`" in footer
    assert "Andromity AI" not in footer
    assert "using" not in review_footer()
